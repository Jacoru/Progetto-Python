print(df[df['xg'].isna()][['date', 'round', 'team', 'opponent', 'xg', 'xga', 'sh', 'sot', 'dist', "pk", 'notes']])

"""
The missing values are generated by one match (matchday 1) because the match awarded to Hellas Verona. 
To impute the missing we can compute the value of xg and xga.
Xg_totali = (pk *W_pk) + (sot *W_porta) + (sh-sot *W_fuori) - (dist *W_distanza)
The following weights (W_pk = 0.76, \(W_{porta}=0.18\), \(W_{fuori}=0.04\), \(W_{distanza}=0.006\)) are standard coefficients optimized
by studying the averages of thousands of Serie A and Premier League matches. 
"""
#print(df.loc[3370, ["pk", "sot", "sh", "dist"]])
"The distance variable is missing so i compute the average distance of the other matches played by the same team"
df.loc[3370, "dist"] = df[df["team"] == df.loc[3370, "team"]]["dist"].mean().round(2)
print(df.loc[3370, ["pk", "sot", "sh", "dist"]])


df.loc[[3370], "xg"] = (
    df.loc[[3370], "pk"] * (0.76)
    + df.loc[[3370], "sot"] * (0.18)
    + (df.loc[[3370], "sh"] - df.loc[[3370], "sot"]) * (0.04)
    - df.loc[[3370], "dist"] * (0.006)
).round(2)

df.loc[3484, "dist"] = df[df["team"] == df.loc[3484, "team"]]["dist"].mean().round(2)

df.loc[[3484], "xg"] = (
    df.loc[[3484], "pk"] * (0.76)
    + df.loc[[3484], "sot"] * (0.18)
    + (df.loc[[3484], "sh"] - df.loc[[3484], "sot"]) * (0.04)
    - df.loc[[3484], "dist"] * (0.006)
).round(2)

df.loc[[3370], "xga"]= (df.loc[3484, "xg"])
df.loc[[3484], "xga"]= (df.loc[3370, "xg"])

print(df.loc[[3370], ["xg", "xga"]])
print(df.loc[[3484], ["xg", "xga"]])
